function hexLum(hex) {
  const h = String(hex || '').replace('#', '');
  if (h.length < 6) return 0;
  const r = parseInt(h.slice(0, 2), 16) / 255;
  const g = parseInt(h.slice(2, 4), 16) / 255;
  const b = parseInt(h.slice(4, 6), 16) / 255;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function hexToRgb(hex) {
  const h = String(hex || '').replace('#', '');
  if (h.length < 6) return [0, 0, 0];
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

export function rgbToHex(r, g, b) {
  const c = (n) => Math.max(0, Math.min(255, Math.round(n))).toString(16).padStart(2, '0');
  return `#${c(r)}${c(g)}${c(b)}`;
}

export function normalizeHex(input) {
  let s = String(input || '').trim().replace(/^#/, '');
  if (/^[0-9a-fA-F]{3}$/.test(s)) s = s.split('').map((c) => c + c).join('');
  if (!/^[0-9a-fA-F]{6}$/.test(s)) return null;
  return `#${s.toUpperCase()}`;
}

export function hexToHsv(hex) {
  const [r0, g0, b0] = hexToRgb(normalizeHex(hex) || '#000000');
  const r = r0 / 255;
  const g = g0 / 255;
  const b = b0 / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const d = max - min;
  let h = 0;
  if (d !== 0) {
    if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) / 6;
    else if (max === g) h = ((b - r) / d + 2) / 6;
    else h = ((r - g) / d + 4) / 6;
  }
  return { h: h * 360, s: max === 0 ? 0 : d / max, v: max };
}

export function hsvToHex(h, s, v) {
  const hh = ((h % 360) + 360) % 360;
  const ss = Math.max(0, Math.min(1, s));
  const vv = Math.max(0, Math.min(1, v));
  const c = vv * ss;
  const x = c * (1 - Math.abs(((hh / 60) % 2) - 1));
  const m = vv - c;
  let r = 0;
  let g = 0;
  let b = 0;
  if (hh < 60) [r, g, b] = [c, x, 0];
  else if (hh < 120) [r, g, b] = [x, c, 0];
  else if (hh < 180) [r, g, b] = [0, c, x];
  else if (hh < 240) [r, g, b] = [0, x, c];
  else if (hh < 300) [r, g, b] = [x, 0, c];
  else [r, g, b] = [c, 0, x];
  return rgbToHex((r + m) * 255, (g + m) * 255, (b + m) * 255);
}

export function mixHex(a, b, t) {
  const A = hexToRgb(a);
  const B = hexToRgb(b);
  return rgbToHex(A[0] + (B[0] - A[0]) * t, A[1] + (B[1] - A[1]) * t, A[2] + (B[2] - A[2]) * t);
}

function pickSwatchHex(id, swatches, scheme, customHex) {
  const custom = normalizeHex(customHex);
  if (id === CUSTOM_COLOR_ID && custom) return custom;
  const s = swatches.find((x) => x.id === id);
  if (!s) return custom || (scheme === 'light' ? swatches[0].light : swatches[0].dark);
  return scheme === 'light' ? s.light : s.dark;
}

export function resolvePalette(scheme = 'dark', accentId = DEFAULT_ACCENT_ID, chartId = DEFAULT_CHART_ID, custom = {}) {
  const base = palettes[scheme] || palettes.dark;
  const accent = pickSwatchHex(accentId, ACCENT_SWATCHES, scheme, custom.accent);
  const chartAccent = pickSwatchHex(chartId, CHART_SWATCHES, scheme, custom.chart);
  const accentFg = hexLum(accent) > 0.62 ? '#141414' : '#F4F4F2';
  const chartFg = hexLum(chartAccent) > 0.62 ? '#141414' : '#F4F4F2';
  const bg = base.background;
  const restMix = scheme === 'dark' ? 0.58 : 0.5;
  return {
    ...base,
    accent,
    accentBorder: accent,
    primary: accent,
    primaryLight: accent,
    blue: accent,
    indigo: accent,
    accentFg,
    chartAccent,
    chartFg,
    heatmapWork: chartAccent,
    heatmapRest: mixHex(chartAccent, bg, restMix),
    accentSoftFill: mixHex(accent, base.surface, scheme === 'dark' ? 0.78 : 0.72),
    chartRings: [
      mixHex(chartAccent, bg, 0.78),
      mixHex(chartAccent, bg, 0.6),
      mixHex(chartAccent, bg, 0.42),
      mixHex(chartAccent, bg, 0.24),
      chartAccent,
    ],
  };
}

